-- TV Time: schema "tvtime", movies and series you watch. Safe to run again;
-- install.sh applies it.
--
-- tvtime.movies        one row per movie: watchlist or watched (with the date and
--                      how many times rewatched).
-- tvtime.series        one row per series: watchlist, new (not started yet), watching,
--                      up_to_date, paused or finished, with episodes watched out of the total.
-- tvtime.genres        IMDb's genres; movie_genres / series_genres link titles to them.
--
-- Titles are identified by their IMDb id (tt...). Genres, runtime, end year and
-- episode totals come from IMDb's datasets (sync.sh); poster_url is the link to
-- IMDb's poster image, shown by the page straight from IMDb's image server.
--
-- The page calls the functions at the end through PostgREST (/api/rpc/<fn> with
-- the "tvtime" profile). They're SECURITY DEFINER: the API role (home_web) can
-- call them and nothing else in this schema.

create schema if not exists tvtime;

create table if not exists tvtime.genres (
    id integer generated by default as identity primary key,
    name text not null unique
);

create table if not exists tvtime.movies (
    id integer generated by default as identity primary key,
    imdb_id text unique check (imdb_id ~ '^tt[0-9]+$'),
    title text not null check (length(title) between 1 and 300),
    year smallint,
    status text not null default 'watched' check (status in ('watchlist', 'watched')),
    watched_on date,
    rewatch_count integer not null default 0 check (rewatch_count >= 0),
    runtime_min integer,
    poster_url text,
    imdb_synced_at timestamptz,      -- last time sync.sh found it in IMDb's datasets
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);

create table if not exists tvtime.series (
    id integer generated by default as identity primary key,
    imdb_id text unique check (imdb_id ~ '^tt[0-9]+$'),
    title text not null check (length(title) between 1 and 300),
    year smallint,
    end_year smallint,               -- null: still running (or unknown)
    status text not null default 'watching' check (status in
        ('watchlist', 'new', 'watching', 'up_to_date', 'paused', 'finished')),
    episodes_watched integer not null default 0 check (episodes_watched >= 0),
    total_episodes integer check (total_episodes >= 0),   -- aired episodes, from IMDb
    last_watched_on date,
    runtime_min integer,             -- per episode
    poster_url text,
    imdb_synced_at timestamptz,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);
-- The status list grew ('new'); existing tables get the current check.
alter table tvtime.series drop constraint if exists series_status_check;
alter table tvtime.series add constraint series_status_check check (status in
    ('watchlist', 'new', 'watching', 'up_to_date', 'paused', 'finished'));


create table if not exists tvtime.movie_genres (
    movie_id integer not null references tvtime.movies(id) on delete cascade,
    genre_id integer not null references tvtime.genres(id) on delete cascade,
    primary key (movie_id, genre_id)
);
create table if not exists tvtime.series_genres (
    series_id integer not null references tvtime.series(id) on delete cascade,
    genre_id integer not null references tvtime.genres(id) on delete cascade,
    primary key (series_id, genre_id)
);

-- updated_at on every update (Termux's Postgres has no moddatetime).
create or replace function tvtime.touch() returns trigger language plpgsql as $$
begin
  new.updated_at := now();
  return new;
end $$;
drop trigger if exists movies_mtime on tvtime.movies;
create trigger movies_mtime before update on tvtime.movies for each row execute function tvtime.touch();
drop trigger if exists series_mtime on tvtime.series;
create trigger series_mtime before update on tvtime.series for each row execute function tvtime.touch();

-- ---- API ----------------------------------------------------------------------
-- Errors use SQLSTATEs PostgREST maps to HTTP: 23505 -> 409, PT404 -> 404,
-- 22023 -> 400; the page shows the message.

create or replace function tvtime.movie_json(m tvtime.movies) returns jsonb
language sql stable
as $$
  select jsonb_build_object(
    'id', m.id, 'imdb_id', m.imdb_id, 'title', m.title, 'year', m.year, 'status', m.status,
    'watched_on', m.watched_on, 'rewatch_count', m.rewatch_count, 'runtime_min', m.runtime_min,
    'poster_url', m.poster_url, 'created_at', m.created_at,
    'genres', coalesce((select jsonb_agg(g.name order by g.name) from tvtime.movie_genres mg
                        join tvtime.genres g on g.id = mg.genre_id where mg.movie_id = m.id), '[]'::jsonb))
$$;

create or replace function tvtime.series_json(s tvtime.series) returns jsonb
language sql stable
as $$
  select jsonb_build_object(
    'id', s.id, 'imdb_id', s.imdb_id, 'title', s.title, 'year', s.year, 'end_year', s.end_year,
    'status', s.status, 'episodes_watched', s.episodes_watched, 'total_episodes', s.total_episodes,
    'last_watched_on', s.last_watched_on, 'runtime_min', s.runtime_min, 'poster_url', s.poster_url,
    'created_at', s.created_at, 'updated_at', s.updated_at,
    'genres', coalesce((select jsonb_agg(g.name order by g.name) from tvtime.series_genres sg
                        join tvtime.genres g on g.id = sg.genre_id where sg.series_id = s.id), '[]'::jsonb))
$$;

-- Everything the page shows.
create or replace function tvtime.state() returns jsonb
language sql stable security definer
set search_path = pg_catalog, tvtime
as $$
  select jsonb_build_object(
    'today', current_date,
    'movies', coalesce((select jsonb_agg(tvtime.movie_json(m) order by m.watched_on desc nulls first, m.id desc)
                        from tvtime.movies m), '[]'::jsonb),
    'series', coalesce((select jsonb_agg(tvtime.series_json(s) order by s.updated_at desc, s.id desc)
                        from tvtime.series s), '[]'::jsonb))
$$;

-- An IMDb id from an id or any IMDb link (".../title/tt0903747/...").
create or replace function tvtime.imdb_id(input text) returns text
language sql immutable
as $$ select substring(coalesce(input, '') from 'tt[0-9]{5,}') $$;

create or replace function tvtime.add_movie(imdb_id text, title text, year int default null, poster_url text default null,
                                            status text default 'watched', watched_on date default null) returns jsonb
language plpgsql security definer
set search_path = pg_catalog, tvtime
as $$
declare
  m tvtime.movies;
begin
  if btrim(coalesce(title, '')) = '' then
    raise exception 'The movie needs a title' using errcode = '22023';
  end if;
  insert into tvtime.movies (imdb_id, title, year, poster_url, status, watched_on)
  values (tvtime.imdb_id(add_movie.imdb_id), btrim(add_movie.title), add_movie.year, nullif(add_movie.poster_url, ''),
          coalesce(add_movie.status, 'watched'),
          case when coalesce(add_movie.status, 'watched') = 'watched' then coalesce(add_movie.watched_on, current_date) end)
  returning * into m;
  return tvtime.movie_json(m);
exception
  when unique_violation then raise exception 'That movie is already in your list' using errcode = '23505';
  when check_violation then raise exception 'Invalid value (%)', sqlerrm using errcode = '22023';
end $$;

create or replace function tvtime.add_series(imdb_id text, title text, year int default null, poster_url text default null,
                                             status text default 'watching', episodes_watched int default 0) returns jsonb
language plpgsql security definer
set search_path = pg_catalog, tvtime
as $$
declare
  s tvtime.series;
begin
  if btrim(coalesce(title, '')) = '' then
    raise exception 'The series needs a title' using errcode = '22023';
  end if;
  insert into tvtime.series (imdb_id, title, year, poster_url, status, episodes_watched, last_watched_on)
  values (tvtime.imdb_id(add_series.imdb_id), btrim(add_series.title), add_series.year, nullif(add_series.poster_url, ''),
          coalesce(add_series.status, 'watching'), coalesce(add_series.episodes_watched, 0),
          case when coalesce(add_series.episodes_watched, 0) > 0 then current_date end)
  returning * into s;
  return tvtime.series_json(s);
exception
  when unique_violation then raise exception 'That series is already in your list' using errcode = '23505';
  when check_violation then raise exception 'Invalid value (%)', sqlerrm using errcode = '22023';
end $$;

-- patch: any of title, year, status, watched_on, rewatch_count. Moving a movie to
-- watched without a date sets today.
create or replace function tvtime.update_movie(movie_id int, patch jsonb) returns jsonb
language plpgsql security definer
set search_path = pg_catalog, tvtime
as $$
declare
  m tvtime.movies;
begin
  update tvtime.movies t set
    title = case when patch ? 'title' and btrim(coalesce(patch->>'title', '')) <> '' then btrim(patch->>'title') else t.title end,
    year = case when patch ? 'year' then (patch->>'year')::smallint else t.year end,
    status = coalesce(patch->>'status', t.status),
    watched_on = case when patch ? 'watched_on' then (patch->>'watched_on')::date
                      when coalesce(patch->>'status', t.status) = 'watched' and t.watched_on is null then current_date
                      else t.watched_on end,
    rewatch_count = case when patch ? 'rewatch_count' then greatest(0, (patch->>'rewatch_count')::int) else t.rewatch_count end
  where t.id = update_movie.movie_id
  returning * into m;
  if m.id is null then
    raise exception 'No such movie' using errcode = 'PT404';
  end if;
  return tvtime.movie_json(m);
exception
  when sqlstate 'PT404' then raise;
  when check_violation or invalid_text_representation or invalid_datetime_format or datetime_field_overflow then
    raise exception 'Invalid value (%)', sqlerrm using errcode = '22023';
end $$;

-- patch: any of title, year, status, episodes_watched, total_episodes.
create or replace function tvtime.update_series(series_id int, patch jsonb) returns jsonb
language plpgsql security definer
set search_path = pg_catalog, tvtime
as $$
declare
  s tvtime.series;
begin
  update tvtime.series t set
    title = case when patch ? 'title' and btrim(coalesce(patch->>'title', '')) <> '' then btrim(patch->>'title') else t.title end,
    year = case when patch ? 'year' then (patch->>'year')::smallint else t.year end,
    status = coalesce(patch->>'status', t.status),
    episodes_watched = case when patch ? 'episodes_watched' then greatest(0, (patch->>'episodes_watched')::int) else t.episodes_watched end,
    total_episodes = case when patch ? 'total_episodes' then (patch->>'total_episodes')::int else t.total_episodes end
  where t.id = update_series.series_id
  returning * into s;
  if s.id is null then
    raise exception 'No such series' using errcode = 'PT404';
  end if;
  return tvtime.series_json(s);
exception
  when sqlstate 'PT404' then raise;
  when check_violation or invalid_text_representation or numeric_value_out_of_range then
    raise exception 'Invalid value (%)', sqlerrm using errcode = '22023';
end $$;

-- Watched one more (delta 1) or one fewer (-1) episode. Reaching the total marks
-- the series finished (it has ended) or up to date (still running); watching
-- again moves a watchlist / new / paused / up-to-date series to watching.
create or replace function tvtime.episode(series_id int, delta int default 1) returns jsonb
language plpgsql security definer
set search_path = pg_catalog, tvtime
as $$
declare
  s tvtime.series;
  watched int;
begin
  select * into s from tvtime.series where id = episode.series_id for update;
  if not found then
    raise exception 'No such series' using errcode = 'PT404';
  end if;
  watched := greatest(0, s.episodes_watched + coalesce(delta, 1));
  update tvtime.series t set
    episodes_watched = watched,
    last_watched_on = case when delta > 0 then current_date else t.last_watched_on end,
    status = case
      when t.total_episodes is not null and watched >= t.total_episodes and t.total_episodes > 0
        then case when t.end_year is not null then 'finished' else 'up_to_date' end
      when delta > 0 and t.status in ('watchlist', 'new', 'paused', 'up_to_date', 'finished') then 'watching'
      when delta < 0 and t.status in ('up_to_date', 'finished') then 'watching'
      else t.status end
  where t.id = s.id
  returning * into s;
  return tvtime.series_json(s);
end $$;

-- A rewatch: one more in the count.
create or replace function tvtime.rewatch(movie_id int) returns jsonb
language plpgsql security definer
set search_path = pg_catalog, tvtime
as $$
declare
  m tvtime.movies;
begin
  update tvtime.movies set rewatch_count = rewatch_count + 1 where id = rewatch.movie_id returning * into m;
  if m.id is null then
    raise exception 'No such movie' using errcode = 'PT404';
  end if;
  return tvtime.movie_json(m);
end $$;

create or replace function tvtime.delete_movie(movie_id int) returns void
language sql security definer
set search_path = pg_catalog, tvtime
as $$ delete from tvtime.movies where id = delete_movie.movie_id $$;

create or replace function tvtime.delete_series(series_id int) returns void
language sql security definer
set search_path = pg_catalog, tvtime
as $$ delete from tvtime.series where id = delete_series.series_id $$;

-- Search IMDb by name or id (IMDb's own search suggestions): up to 8 movies and
-- series, with the poster link and whether it's already in your lists.
create or replace function tvtime.search(q text) returns jsonb
language plpython3u stable security definer
set search_path = pg_catalog, tvtime
as $py$
import json, re, urllib.parse, urllib.request

# (PL/Python arguments act as globals: assigning to q here would break it.)
text = (q or "").strip()
m = re.search(r"tt\d{5,}", text)
key = m.group(0) if m else text.lower()
if len(key) < 2:
    return "[]"
url = "https://v3.sg.media-imdb.com/suggestion/x/" + urllib.parse.quote(key) + ".json"
req = urllib.request.Request(url, headers={"User-Agent": "Mozilla/5.0 (exocortex tvtime)"})
try:
    with urllib.request.urlopen(req, timeout=8) as r:
        data = json.load(r)
except Exception as e:
    plpy.error(f"IMDb search didn't answer ({type(e).__name__})")

KINDS = {"movie": "movie", "tvMovie": "movie", "video": "movie",
         "tvSeries": "series", "tvMiniSeries": "series"}
have = {r["imdb_id"]: r["kind"] for r in plpy.execute(
    "select imdb_id, 'movie' as kind from tvtime.movies where imdb_id is not null "
    "union all select imdb_id, 'series' from tvtime.series where imdb_id is not null")}
out = []
for x in data.get("d", []):
    kind = KINDS.get(x.get("qid"))
    if not kind or not str(x.get("id", "")).startswith("tt"):
        continue
    out.append({
        "imdb_id": x["id"], "title": x.get("l"), "year": x.get("y"), "years": x.get("yr"),
        "kind": kind, "type": x.get("q"), "cast": x.get("s"),
        "poster_url": (x.get("i") or {}).get("imageUrl"),
        "in_list": have.get(x["id"]),
    })
return json.dumps(out[:8])
$py$;

